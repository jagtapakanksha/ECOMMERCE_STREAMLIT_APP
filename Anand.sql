
-- E-commerce project database
CREATE DATABASE IF NOT EXISTS ECOMMERCE_DB;
--CREATE OR REPLACE DATABASE ECOMMERCE_DB;

-- Three layers
CREATE SCHEMA IF NOT EXISTS ECOMMERCE_DB.RAW;
CREATE SCHEMA IF NOT EXISTS ECOMMERCE_DB.STAGING;
CREATE SCHEMA IF NOT EXISTS ECOMMERCE_DB.ANALYTICS;

-- Select the database and RAW schema
USE DATABASE ECOMMERCE_DB;
USE SCHEMA RAW;

-- File format for the Olist CSV files
CREATE OR REPLACE FILE FORMAT CSV_FORMAT
    TYPE = CSV
    FIELD_DELIMITER = ','
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    EMPTY_FIELD_AS_NULL = TRUE
    NULL_IF = ('NULL', 'null')
    TRIM_SPACE = FALSE
    ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE;

-- Internal stage for uploading the source files
CREATE STAGE IF NOT EXISTS RAW_STAGE
    FILE_FORMAT = CSV_FORMAT;


--Creating table

CREATE TABLE IF NOT EXISTS RAW_CUSTOMERS (
    CUSTOMER_ID VARCHAR,
    CUSTOMER_UNIQUE_ID VARCHAR,
    CUSTOMER_ZIP_CODE_PREFIX VARCHAR,
    CUSTOMER_CITY VARCHAR,
    CUSTOMER_STATE VARCHAR,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS RAW_GEOLOCATION (
    GEOLOCATION_ZIP_CODE_PREFIX VARCHAR,
    GEOLOCATION_LAT VARCHAR,
    GEOLOCATION_LNG VARCHAR,
    GEOLOCATION_CITY VARCHAR,
    GEOLOCATION_STATE VARCHAR,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS RAW_ORDER_ITEMS (
    ORDER_ID VARCHAR,
    ORDER_ITEM_ID VARCHAR,
    PRODUCT_ID VARCHAR,
    SELLER_ID VARCHAR,
    SHIPPING_LIMIT_DATE VARCHAR,
    PRICE VARCHAR,
    FREIGHT_VALUE VARCHAR,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS RAW_ORDER_PAYMENTS (
    ORDER_ID VARCHAR,
    PAYMENT_SEQUENTIAL VARCHAR,
    PAYMENT_TYPE VARCHAR,
    PAYMENT_INSTALLMENTS VARCHAR,
    PAYMENT_VALUE VARCHAR,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS RAW_ORDER_REVIEWS (
    REVIEW_ID VARCHAR,
    ORDER_ID VARCHAR,
    REVIEW_SCORE VARCHAR,
    REVIEW_COMMENT_TITLE VARCHAR,
    REVIEW_COMMENT_MESSAGE VARCHAR,
    REVIEW_CREATION_DATE VARCHAR,
    REVIEW_ANSWER_TIMESTAMP VARCHAR,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS RAW_ORDERS (
    ORDER_ID VARCHAR,
    CUSTOMER_ID VARCHAR,
    ORDER_STATUS VARCHAR,
    ORDER_PURCHASE_TIMESTAMP VARCHAR,
    ORDER_APPROVED_AT VARCHAR,
    ORDER_DELIVERED_CARRIER_DATE VARCHAR,
    ORDER_DELIVERED_CUSTOMER_DATE VARCHAR,
    ORDER_ESTIMATED_DELIVERY_DATE VARCHAR,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS RAW_PRODUCTS (
    PRODUCT_ID VARCHAR,
    PRODUCT_CATEGORY_NAME VARCHAR,
    PRODUCT_NAME_LENGHT VARCHAR,
    PRODUCT_DESCRIPTION_LENGHT VARCHAR,
    PRODUCT_PHOTOS_QTY VARCHAR,
    PRODUCT_WEIGHT_G VARCHAR,
    PRODUCT_LENGTH_CM VARCHAR,
    PRODUCT_HEIGHT_CM VARCHAR,
    PRODUCT_WIDTH_CM VARCHAR,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS RAW_SELLERS (
    SELLER_ID VARCHAR,
    SELLER_ZIP_CODE_PREFIX VARCHAR,
    SELLER_CITY VARCHAR,
    SELLER_STATE VARCHAR,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

--Load data from STAGE using COPY INTO Command

COPY INTO RAW_CUSTOMERS (
    CUSTOMER_ID, CUSTOMER_UNIQUE_ID,
    CUSTOMER_ZIP_CODE_PREFIX, CUSTOMER_CITY, CUSTOMER_STATE
)
FROM @RAW_STAGE
FILES = ('customers.csv')
FILE_FORMAT = (FORMAT_NAME = CSV_FORMAT)
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO RAW_GEOLOCATION (
    GEOLOCATION_ZIP_CODE_PREFIX, GEOLOCATION_LAT,
    GEOLOCATION_LNG, GEOLOCATION_CITY, GEOLOCATION_STATE
)
FROM @RAW_STAGE
FILES = ('geolocation.csv')
FILE_FORMAT = (FORMAT_NAME = CSV_FORMAT)
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO RAW_ORDER_ITEMS (
    ORDER_ID, ORDER_ITEM_ID, PRODUCT_ID, SELLER_ID,
    SHIPPING_LIMIT_DATE, PRICE, FREIGHT_VALUE
)
FROM @RAW_STAGE
FILES = ('order_items.csv')
FILE_FORMAT = (FORMAT_NAME = CSV_FORMAT)
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO RAW_ORDER_PAYMENTS (
    ORDER_ID, PAYMENT_SEQUENTIAL, PAYMENT_TYPE,
    PAYMENT_INSTALLMENTS, PAYMENT_VALUE
)
FROM @RAW_STAGE
FILES = ('order_payments.csv')
FILE_FORMAT = (FORMAT_NAME = CSV_FORMAT)
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO RAW_ORDER_REVIEWS (
    REVIEW_ID, ORDER_ID, REVIEW_SCORE,
    REVIEW_COMMENT_TITLE, REVIEW_COMMENT_MESSAGE,
    REVIEW_CREATION_DATE, REVIEW_ANSWER_TIMESTAMP
)
FROM @RAW_STAGE
FILES = ('order_reviews.csv')
FILE_FORMAT = (FORMAT_NAME = CSV_FORMAT)
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO RAW_ORDERS (
    ORDER_ID, CUSTOMER_ID, ORDER_STATUS,
    ORDER_PURCHASE_TIMESTAMP, ORDER_APPROVED_AT,
    ORDER_DELIVERED_CARRIER_DATE,
    ORDER_DELIVERED_CUSTOMER_DATE,
    ORDER_ESTIMATED_DELIVERY_DATE
)
FROM @RAW_STAGE
FILES = ('orders.csv')
FILE_FORMAT = (FORMAT_NAME = CSV_FORMAT)
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO RAW_PRODUCTS (
    PRODUCT_ID, PRODUCT_CATEGORY_NAME,
    PRODUCT_NAME_LENGHT, PRODUCT_DESCRIPTION_LENGHT,
    PRODUCT_PHOTOS_QTY, PRODUCT_WEIGHT_G,
    PRODUCT_LENGTH_CM, PRODUCT_HEIGHT_CM, PRODUCT_WIDTH_CM
)
FROM @RAW_STAGE
FILES = ('products.csv')
FILE_FORMAT = (FORMAT_NAME = CSV_FORMAT)
ON_ERROR = 'ABORT_STATEMENT';

COPY INTO RAW_SELLERS (
    SELLER_ID, SELLER_ZIP_CODE_PREFIX,
    SELLER_CITY, SELLER_STATE
)
FROM @RAW_STAGE
FILES = ('sellers.csv')
FILE_FORMAT = (FORMAT_NAME = CSV_FORMAT)
ON_ERROR = 'ABORT_STATEMENT';

--Validate the Raw Layer
